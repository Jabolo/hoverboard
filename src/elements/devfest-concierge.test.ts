import { afterEach, describe, expect, it, jest } from '@jest/globals';
import agenda from '../../public/data/agenda-2026.json';
import programme from '../../public/data/programme-2026.json';
import type { A2UIMessage } from '../concierge/a2ui-protocol';
import { setSessionFavorite } from '../utils/session-favorites';
import { DevfestConcierge } from './devfest-concierge';

function mockBootstrapFetch(conciergeResponder?: () => Promise<Response>): jest.Mock<typeof fetch> {
  return jest.fn<typeof fetch>(async (input, _init) => {
    const url = String(input);
    if (url.includes('/data/agenda-2026.json')) {
      return { ok: true, status: 200, json: async () => agenda } as Response;
    }
    if (url.includes('/data/programme-2026.json')) {
      return { ok: true, status: 200, json: async () => programme } as Response;
    }
    if (url.includes('/api/cloud-credit')) {
      return { ok: true, status: 200, json: async () => ({ status: 'upcoming' }) } as Response;
    }
    if (url.includes('/api/concierge') && conciergeResponder) {
      return conciergeResponder();
    }
    return { ok: false, status: 404, json: async () => ({}) } as Response;
  });
}

async function flushRender(element: DevfestConcierge): Promise<void> {
  await new Promise((resolve) => setTimeout(resolve, 0));
  await element.updateComplete;
  await new Promise((resolve) => setTimeout(resolve, 0));
  await element.updateComplete;
}

describe('devfest-concierge', () => {
  const originalFetch = globalThis.fetch;

  afterEach(() => {
    document.body.replaceChildren();
    globalThis.fetch = originalFetch;
    window.localStorage.clear();
    jest.restoreAllMocks();
  });

  it('renders an immediate grounded local A2UI surface on load without calling /api/concierge', async () => {
    const fetchMock = mockBootstrapFetch();
    globalThis.fetch = fetchMock;

    const element = new DevfestConcierge();
    document.body.appendChild(element);
    await flushRender(element);

    const root = element.shadowRoot!;
    expect(root.querySelector('.source-badge')?.textContent?.trim()).toBe(
      'A2UI · Grounded Local Engine',
    );
    expect(root.querySelector('.surface-title')?.textContent).toBeTruthy();
    expect(root.querySelectorAll('.intent-chip')).toHaveLength(6);

    const conciergeCalls = fetchMock.mock.calls.filter((call) =>
      String(call[0]).includes('/api/concierge'),
    );
    expect(conciergeCalls).toHaveLength(0);
  });

  it('renders live A2UI messages from /api/concierge when available', async () => {
    const liveMessages: A2UIMessage[] = [
      {
        type: 'createSurface',
        surfaceId: 'live-surface',
        title: 'Live AI Track',
        source: 'gemini-4-hydrogen',
        timestamp: Date.now(),
      },
      {
        type: 'updateDataModel',
        surfaceId: 'live-surface',
        data: {
          savedSessions: { 'CFP-021': false },
          conflicts: {},
        },
      },
      {
        type: 'updateComponents',
        surfaceId: 'live-surface',
        rootId: 'live-root',
        components: [
          {
            id: 'live-root',
            component: 'SurfaceContainer',
            parentId: null,
            children: ['live-banner', 'live-session'],
            props: {
              title: 'Live AI Track',
              subtitle: 'Generated by Gemini 4 Hydrogen',
            },
          },
          {
            id: 'live-banner',
            component: 'CalloutBanner',
            parentId: 'live-root',
            props: {
              tone: 'success',
              title: 'Live A2UI Surface Ready',
              body: 'Non-overlapping picks.',
            },
          },
          {
            id: 'live-session',
            component: 'SessionCard',
            parentId: 'live-root',
            props: {
              sessionId: 'CFP-021',
              title: 'Autonomous Agents in Production',
              start: '10:15',
              end: '10:55',
              space: 'Auditorium',
              kind: 'Talk',
              speakers: ['Ada Lovelace'],
              href: '/sessions/CFP-021/',
              reason: 'Directly matches AI & Agents track.',
            },
            bindings: {
              saved: 'savedSessions.CFP-021',
              conflict: 'conflicts.CFP-021',
            },
          },
        ],
      },
    ];

    globalThis.fetch = mockBootstrapFetch(
      async () =>
        ({
          ok: true,
          status: 200,
          json: async () => ({ messages: liveMessages }),
        }) as Response,
    );

    const element = new DevfestConcierge();
    document.body.appendChild(element);
    await flushRender(element);

    const aiChip = element.shadowRoot?.querySelector<HTMLButtonElement>(
      'button[data-intent="track-ai"]',
    );
    expect(aiChip).not.toBeNull();
    aiChip!.click();
    await flushRender(element);

    const root = element.shadowRoot!;
    expect(root.querySelector('.source-badge')?.textContent?.trim()).toBe(
      'A2UI · Gemini 4 Hydrogen (Medium)',
    );
    expect(root.querySelector('.surface-title')?.textContent).toBe('Live AI Track');
    expect(root.querySelector('.session-title a')?.getAttribute('href')).toBe('/sessions/CFP-021/');
  });

  it('falls back to the local A2UI engine and shows notice on 429 rate limit', async () => {
    globalThis.fetch = mockBootstrapFetch(
      async () =>
        ({
          ok: false,
          status: 429,
          json: async () => ({ error: 'rate_limited' }),
        }) as Response,
    );

    const element = new DevfestConcierge();
    document.body.appendChild(element);
    await flushRender(element);

    const creditsChip = element.shadowRoot?.querySelector<HTMLButtonElement>(
      'button[data-intent="credits-workshops"]',
    );
    creditsChip!.click();
    await flushRender(element);

    const root = element.shadowRoot!;
    expect(root.querySelector('.source-badge')?.textContent?.trim()).toBe(
      'A2UI · Grounded Local Engine',
    );
    expect(root.querySelector('.status-notice')?.textContent).toContain(
      'Rate limit reached — running on Grounded Local A2UI Engine',
    );
    expect(root.querySelector('.credit-card')).not.toBeNull();
  });

  it('falls back cleanly when /api/concierge throws a network error', async () => {
    globalThis.fetch = mockBootstrapFetch(async () => {
      throw new Error('Network offline');
    });

    const element = new DevfestConcierge();
    document.body.appendChild(element);
    await flushRender(element);

    const input = element.shadowRoot?.querySelector<HTMLInputElement>('#concierge-input');
    input!.value = 'Where is the venue?';
    input!.dispatchEvent(new Event('input'));
    element.shadowRoot
      ?.querySelector<HTMLFormElement>('.prompt-form')
      ?.dispatchEvent(new Event('submit', { cancelable: true }));
    await flushRender(element);

    const root = element.shadowRoot!;
    expect(root.querySelector('.source-badge')?.textContent?.trim()).toBe(
      'A2UI · Grounded Local Engine',
    );
    expect(root.querySelector('.logistics-card')).not.toBeNull();
  });

  it('syncs session bookmarks and updates conflict warnings reactively', async () => {
    globalThis.fetch = mockBootstrapFetch(
      async () =>
        ({
          ok: false,
          status: 503,
          json: async () => ({}),
        }) as Response,
    );

    // Pre-save INVITED-004 (10:15-10:55 Classroom)
    setSessionFavorite('INVITED-004', true);

    const element = new DevfestConcierge();
    document.body.appendChild(element);
    await flushRender(element);

    // Compare rooms at 10:15 shows both CFP-021 (Auditorium) and INVITED-004 (Classroom)
    const compareChip = element.shadowRoot?.querySelector<HTMLButtonElement>(
      'button[data-intent="compare-rooms"]',
    );
    compareChip!.click();
    await flushRender(element);

    const root = element.shadowRoot!;
    const cfpCard = root.querySelector<HTMLElement>(
      'article.session-card[data-session-id="CFP-021"]',
    );
    const saveBtn = cfpCard?.querySelector<HTMLButtonElement>('.save-btn');
    if (saveBtn) {
      expect(saveBtn.getAttribute('aria-pressed')).toBe('false');
      saveBtn.click();
      await flushRender(element);

      const updatedCard = root.querySelector<HTMLElement>(
        'article.session-card[data-session-id="CFP-021"]',
      );
      expect(updatedCard?.querySelector('.save-btn')?.getAttribute('aria-pressed')).toBe('true');
      expect(updatedCard?.querySelector('.save-btn')?.textContent?.trim()).toBe('Saved');
      expect(updatedCard?.querySelector('.conflict-warning')?.textContent).toContain(
        'Schedule conflict:',
      );
    }
  });

  it('toggles Inspect A2UI JSON panel with aria-expanded', async () => {
    globalThis.fetch = mockBootstrapFetch();

    const element = new DevfestConcierge();
    document.body.appendChild(element);
    await flushRender(element);

    const root = element.shadowRoot!;
    const inspectBtn = root.querySelector<HTMLButtonElement>('.inspect-btn')!;
    expect(inspectBtn.getAttribute('aria-expanded')).toBe('false');
    expect(root.querySelector('#a2ui-inspector')).toBeNull();

    inspectBtn.click();
    await element.updateComplete;

    expect(inspectBtn.getAttribute('aria-expanded')).toBe('true');
    const inspector = root.querySelector('#a2ui-inspector');
    expect(inspector).not.toBeNull();
    expect(inspector?.textContent).toContain('"surfaceId"');
    expect(inspector?.textContent).toContain('"SurfaceContainer"');
  });
});
